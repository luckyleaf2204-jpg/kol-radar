"""Build insiders/page/ (index.html + app.js + styles.css) from the SOL Memecoin Hunter dashboard's Insiders code,
so both sites render the same page. Run after changing the Insiders UI in sol_memecoin_hunter:

    python tools/build_insiders_page.py ../sol_hunter_insiders

It copies the Insiders functions of src/web/static/app.js (by name), the Vietnamese strings they use and the
stylesheet, and adds a small shell: access code login, api(), toast and the 30 s alert refresh."""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FUNCS = ["t", "esc", "safeUrl", "usd", "short", "acct", "tks", "insTable", "renderInsiders", "moneyPath", "beep", "insGroup", "coinsHtml", "vipHtml",
         "pingNew", "refreshWatch", "watchHtml", "paperHtml", "treeNode", "treesHtml", "extraHtml", "sol", "pnlHtml",
         "deepHtml", "bindIns"]


def extract(src: str, name: str) -> str:
    m = re.search(rf"^(async )?function {re.escape(name)}\(", src, re.M)
    if not m:
        raise SystemExit(f"function {name} not found")
    i, depth, j = m.start(), 0, src.index("{", m.start())
    for k in range(j, len(src)):
        c = src[k]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return src[i:k + 1]
    raise SystemExit(f"unbalanced {name}")


SHELL = r"""/* Insiders site (KOL Radar host). Generated by tools/build_insiders_page.py from the SOL Memecoin Hunter page. */
"use strict";
const $ = (s) => document.querySelector(s);
const LS = {
  get(k, d) { try { const v = localStorage.getItem(k); return v === null ? d : JSON.parse(v); } catch (_) { return d; } },
  set(k, v) { try { localStorage.setItem(k, JSON.stringify(v)); } catch (_) { /* private mode */ } },
  del(k) { try { localStorage.removeItem(k); } catch (_) { /* ignore */ } },
};
const S = { code: LS.get("insAccessCode", ""), dict: __DICT__, insRunning: false, timer: null };
function toast(msg) { const el = $("#toast"); el.textContent = msg; el.classList.add("on"); clearTimeout(el._t); el._t = setTimeout(() => el.classList.remove("on"), 2600); }
async function api(path, opts = {}) {
  const r = await fetch(path, { method: opts.method || "GET", headers: { "X-Access-Code": S.code, "Content-Type": "application/json" },
    body: opts.body ? JSON.stringify(opts.body) : undefined, cache: "no-store" });
  if (r.status === 401) { showLogin(t("web.login.bad")); throw new Error("auth"); }
  if (!r.ok) throw new Error("http " + r.status);
  return r.json();
}
async function copyText(txt) { try { await navigator.clipboard.writeText(txt); toast(t("web.copied")); } catch (_) { toast(txt); } }
function showLogin(err) {
  $("#view").innerHTML = `<div class="login"><h1>${esc(t("web.title.insiders"))}</h1><p class="muted">${esc(t("web.login.hint"))}</p>
    <input id="code" type="password" placeholder="${esc(t("web.login.placeholder"))}" autocomplete="current-password">
    <button class="btn primary" id="go">${esc(t("web.login.go"))}</button><div class="c-red small">${esc(err || "")}</div></div>`;
  $("#go").onclick = async () => { S.code = $("#code").value.trim(); try { await api("/api/insiders/watch"); LS.set("insAccessCode", S.code); start(); } catch (_) { /* message shown */ } };
}
function start() {
  renderInsiders();
  clearInterval(S.timer);
  S.timer = setInterval(() => { if (document.hidden) return; if (S.insRunning) renderInsiders(true); else refreshWatch(); }, 30000);
}
document.addEventListener("click", (e) => { const cp = e.target.closest("[data-copy]"); if (cp) { e.preventDefault(); copyText(cp.dataset.copy); } });
"""

